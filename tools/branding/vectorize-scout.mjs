// Preparation-only dependencies; no tracing library ships in the app.
import { createRequire } from "node:module";
import { readFile, writeFile } from "node:fs/promises";
const require = createRequire(import.meta.url);
const sharp = require(process.env.SHARP_MODULE || "sharp");
const { Potrace } = require(process.env.POTRACE_MODULE || "potrace");
const root = new URL("../../", import.meta.url);
const { data, info } = await sharp(
  await readFile(new URL("design/branding/scout-logo-master.png", root)),
)
  .ensureAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });
const { width, height } = info;
const count = width * height;
const palette = [
  [23, 55, 79],
  [25, 109, 170],
  [220, 237, 251],
  [255, 254, 254],
];
const masks = palette.map(() => new Uint8Array(count));
const eyes = new Uint8Array(count);
const scale = width / 564;
for (let i = 0; i < count; i++) {
  if (data[i * 4 + 3] < 128) continue;
  const rgb = Array.from(data.subarray(i * 4, i * 4 + 3));
  const distances = palette.map((color) =>
    color.reduce((sum, channel, j) => sum + (channel - rgb[j]) ** 2, 0),
  );
  const color = distances.indexOf(Math.min(...distances));
  const x = (i % width) / scale;
  const y = Math.floor(i / width) / scale;
  const inEye = y > 235 && y < 325 && ((x > 188 && x < 288) || (x > 376 && x < 476));
  if (inEye && (color === 2 || color === 3 || color === 0)) eyes[i] = 1;
  else masks[color][i] = 1;
}
async function trace(mask) {
  const pixels = Buffer.alloc(count, 255);
  mask.forEach((on, i) => {
    if (on) pixels[i] = 0;
  });
  const png = await sharp(pixels, { raw: { width, height, channels: 1 } })
    .png()
    .toBuffer();
  return new Promise((resolve, reject) => {
    const tracer = new Potrace({ threshold: 128, turdSize: 5, optTolerance: 0.35 });
    tracer.loadImage(png, (error) => {
      if (error) return reject(error);
      const svg = tracer.getSVG();
      const path = svg.match(/<path d="([^"]*)"/);
      if (!path) return reject(new Error("Trace produced no path"));
      resolve(path[1]);
    });
  });
}
// Trace stacked solids, not adjacent pieces with independently fitted edges.
// Navy continues underneath blue; blue continues underneath the eye interiors.
// Otherwise their antialiased boundaries expose pale hairline gaps.
const face = masks[0].map((on, i) => on || masks[1][i] || eyes[i]);
const goggles = masks[1].map((on, i) => on || eyes[i]);
// The fleece is also a complete backing for the head, not a cut-out shell.
// Stop above the lettering so it does not gain a white outline.
const wool = masks[3].map(
  (on, i) => on || (Math.floor(i / width) / scale < 465 && (face[i] || masks[2][i])),
);
const layers = await Promise.all(
  [
    ["wool-and-mouth", "#fff", wool],
    ["face-and-wordmark", "#17374f", face],
    ["inner-ear", "#dceefc", masks[2]],
    ["binoculars", "#196daa", goggles],
    ["eyes", "#f5f9fd", eyes],
  ].map(async ([id, fill, mask]) => ({ id, fill, path: await trace(mask) })),
);
const artwork = {
  width,
  height,
  layers,
  eyes: layers.at(-1).path,
  goggles: layers.find((layer) => layer.id === "binoculars").path,
  pupils: [280, 468].map((x) => ({
    cx: x * scale,
    cy: 279 * scale,
    rx: 25 * scale,
    ry: 25 * scale,
  })),
};
await writeFile(
  new URL("src/shared/ui/scoutArtwork.ts", root),
  `// Generated by tools/branding/vectorize-scout.mjs. Do not edit paths by hand.\nexport const scoutArtwork = ${JSON.stringify(artwork, null, 2)} as const;\n`,
);
const pupilMarkup = artwork.pupils
  .map((p) => `<ellipse cx="${p.cx}" cy="${p.cy}" rx="${p.rx}" ry="${p.ry}"/>`)
  .join("");
const svg = `<svg xmlns="http://www.w3.org/2000/svg" fill-rule="evenodd" viewBox="0 0 ${width} ${height}" role="img" aria-labelledby="title"><title id="title">Fernblick</title><defs><clipPath id="goggles"><path d="${artwork.goggles}"/></clipPath></defs>${layers.map((l) => `<path id="${l.id}" fill="${l.fill}" d="${l.path}"/>`).join("")}<g clip-path="url(#goggles)"><g id="pupils" fill="#17374f">${pupilMarkup}</g></g><path id="goggle-rim" fill="#196daa" d="${artwork.goggles} ${artwork.eyes}"/></svg>\n`;
await writeFile(new URL("public/icons/scout-logo.svg", root), svg);
// Match the approved raster crops, including the head's 20px vertical padding.
// The head crop excludes the lettering even in its padded area.
const head = svg
  .replace(`viewBox="0 0 ${width} ${height}"`, 'viewBox="70 -10 800 800" width="800" height="800"')
  .replace(
    "</defs>",
    '<clipPath id="head-crop"><rect x="70" y="10" width="800" height="760"/></clipPath></defs><g clip-path="url(#head-crop)">',
  )
  .replace("</svg>", "</g></svg>");
const wordmarkPath = await trace(masks[0].map((on, i) => on && Math.floor(i / width) >= 775));
const wordmark = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 775 940 210" width="940" height="210" role="img" aria-labelledby="title"><title id="title">Fernblick</title><path fill="#17374f" fill-rule="evenodd" d="${wordmarkPath}"/></svg>\n`;
await writeFile(new URL("public/icons/scout-head.svg", root), head);
await writeFile(new URL("public/icons/scout-wordmark.svg", root), wordmark);
console.log(
  `Vector artwork: ${layers.length} path layers and two independent pupils; exported logo, padded head and wordmark.`,
);
